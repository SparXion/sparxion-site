#!/usr/bin/env node
/**
 * Reads Portfolio/01-MASTERS project images/ dirs and writes portfolioImageManifest.ts
 * Folder name === portfolio id (1:1 with public/portfolio and design band).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const MASTERS = path.join(ROOT, 'Portfolio', '01-MASTERS');
const OUT = path.join(ROOT, 'src', 'data', 'portfolioImageManifest.ts');

const GALLERY_RE = /\.(jpe?g|png|webp)$/i;

function naturalSort(files) {
  return [...files].sort((a, b) =>
    a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }),
  );
}

function listGalleryFromDir(dir) {
  if (!fs.existsSync(dir)) return [];
  const names = fs.readdirSync(dir).filter((name) => {
    if (name.toLowerCase() === 'band.jpg') return false;
    return GALLERY_RE.test(name);
  });
  return naturalSort(names);
}

function buildManifest() {
  /** @type {Record<string, string[]>} */
  const byId = {};
  if (!fs.existsSync(MASTERS)) {
    console.error(`Missing ${MASTERS}`);
    process.exit(1);
  }
  for (const name of fs.readdirSync(MASTERS).sort()) {
    const imgDir = path.join(MASTERS, name, 'images');
    if (!fs.statSync(path.join(MASTERS, name)).isDirectory()) continue;
    if (!fs.existsSync(imgDir)) continue;
    byId[name] = listGalleryFromDir(imgDir);
  }
  return byId;
}

function emitTs(byId) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-portfolio-image-manifest.mjs — do not edit by hand',
    '// Re-run: npm run sync-portfolio',
    '',
    'export const portfolioImageManifest: Readonly<Record<string, readonly string[]>> = {',
  ];
  for (const id of Object.keys(byId).sort()) {
    const files = byId[id];
    lines.push(`  '${id}': [`);
    for (const f of files) {
      lines.push(`    '${f.replace(/'/g, "\\'")}',`);
    }
    lines.push('  ],');
  }
  lines.push('};', '');
  lines.push('export function galleryImagesForPortfolio(id: string): readonly string[] {');
  lines.push('  return portfolioImageManifest[id] ?? [];');
  lines.push('}', '');
  return lines.join('\n');
}

const manifest = buildManifest();
fs.writeFileSync(OUT, emitTs(manifest));
console.log(`Wrote ${OUT}`);
for (const [id, files] of Object.entries(manifest).sort((a, b) => a[0].localeCompare(b[0]))) {
  console.log(`  ${id}: ${files.length} images`);
}
